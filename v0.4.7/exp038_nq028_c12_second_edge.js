// ============================================================
// Real geometric adjacency and face correspondence -- adjacency (computeAdjacency,
// sharedVertexCount, vertClose) is COPIED VERBATIM from
// v0.4.7/exp037_edge_location_and_adjacency.js. Face correspondence (matchFaces) reuses the
// same centroid-distance STRATEGY but with one deliberate, validated refinement -- see note
// above centroid() below.
// ============================================================

const VERTEX_TOL = 1e-5;

function vertClose(a, b, tol = VERTEX_TOL) {
  return Math.abs(a[0] - b[0]) < tol && Math.abs(a[1] - b[1]) < tol && Math.abs(a[2] - b[2]) < tol;
}

function sharedVertexCount(faceA, faceB) {
  let count = 0;
  for (const va of faceA.vertices) {
    for (const vb of faceB.vertices) {
      if (vertClose(va, vb)) {
        count++;
        break;
      }
    }
  }
  return count;
}

function overlapScoreForReport(faceA, faceB) {
  let aInB = 0;
  for (const va of faceA.vertices) {
    if (faceB.vertices.some((vb) => vertClose(va, vb))) aInB++;
  }
  let bInA = 0;
  for (const vb of faceB.vertices) {
    if (faceA.vertices.some((va) => vertClose(va, vb))) bInA++;
  }
  return (aInB + bInA) / (faceA.vertices.length + faceB.vertices.length);
}

function computeAdjacency(targetFace, candidateFaces) {
  return candidateFaces
    .filter((f) => f.index !== targetFace.index)
    .map((f) => ({ index: f.index, sharedVertices: sharedVertexCount(targetFace, f) }))
    .filter((r) => r.sharedVertices >= 2)
    .sort((a, b) => b.sharedVertices - a.sharedVertices);
}

// REFINEMENT vs EXP-037 (discovered and validated against real data while building this
// script -- see knowledge/evidence/2026-08-15_v0.4.7-EXP038.md Section 2 for the full
// derivation): EXP-037 used the raw vertex-average as each face's "centroid." That is
// sensitive to non-uniform tessellation density -- a finely-subdivided fillet arc pulls the
// average disproportionately toward itself. Measured directly against C12 (the real SLDPRT
// file this script parses): C00 faces 4/5 (+Z/-Z), which keep the SAME topological identity
// after the fillet trims one corner, shift by up to 0.0046m under vertex-averaging -- within
// 0.0001m of EXP-037's 0.004m threshold, and uncomfortably close to the ~0.0046m distance from
// the genuinely NEW face (index 6) to its nearest unrelated C00 face. Re-measured with the
// AXIS-ALIGNED BOUNDING-BOX CENTER instead (insensitive to point density, only to extent):
// every genuine same-face shift across ALL five archived pairs (C03, C09, C04, C10, and this
// new C12) drops to <=0.0005m, while the new face's distance to its nearest unrelated existing
// face stays ~0.0045m and the minimum distinct-face separation stays ~0.0071m -- both
// essentially unchanged, since they depend on face extent/position, not point density. This
// gives a >=9x safety margin on both sides of the threshold, computed from the corpus's own
// data (not hand-tuned to produce a particular NQ-028 answer -- verified against C03/C09/C04/
// C10 as well as C12 before being adopted). EXP-037's original file and results are NOT
// modified; this refinement applies only within this script.
function centroid(face) {
  let minX = Infinity, minY = Infinity, minZ = Infinity;
  let maxX = -Infinity, maxY = -Infinity, maxZ = -Infinity;
  for (const v of face.vertices) {
    if (v[0] < minX) minX = v[0]; if (v[0] > maxX) maxX = v[0];
    if (v[1] < minY) minY = v[1]; if (v[1] > maxY) maxY = v[1];
    if (v[2] < minZ) minZ = v[2]; if (v[2] > maxZ) maxZ = v[2];
  }
  return [(minX + maxX) / 2, (minY + maxY) / 2, (minZ + maxZ) / 2];
}

function dist3(a, b) {
  return Math.sqrt((a[0] - b[0]) ** 2 + (a[1] - b[1]) ** 2 + (a[2] - b[2]) ** 2);
}

const CENTROID_THRESHOLD = 0.002; // see refinement note above centroid(): safely between the
// largest observed same-face bbox-center shift (~0.0005m) and the nearest new-face/unrelated-
// face distance (~0.0045m), across all five tested pairs.
const AMBIGUITY_MARGIN = 0.0005;

function matchFaces(facesA, facesB) {
  const pairs = [];
  for (const a of facesA) {
    const ca = centroid(a);
    for (const b of facesB) {
      const cb = centroid(b);
      const d = dist3(ca, cb);
      if (d <= CENTROID_THRESHOLD) pairs.push({ a, b, dist: d, overlap: overlapScoreForReport(a, b) });
    }
  }
  pairs.sort((p, q) => p.dist - q.dist);

  const usedA = new Set();
  const usedB = new Set();
  const matched = [];
  const ambiguous = [];

  const candidatesByB = new Map();
  for (const p of pairs) {
    if (!candidatesByB.has(p.b.index)) candidatesByB.set(p.b.index, []);
    candidatesByB.get(p.b.index).push(p);
  }
  const ambiguousB = new Set();
  for (const [bIdx, cands] of candidatesByB) {
    cands.sort((x, y) => x.dist - y.dist);
    if (cands.length >= 2) {
      const gap = cands[1].dist - cands[0].dist;
      if (gap < AMBIGUITY_MARGIN) {
        ambiguousB.add(bIdx);
        ambiguous.push({
          bIndex: bIdx,
          candidates: cands.slice(0, 3).map((c) => ({ aIndex: c.a.index, centroidDist: c.dist })),
        });
      }
    }
  }

  for (const p of pairs) {
    if (usedA.has(p.a.index) || usedB.has(p.b.index)) continue;
    if (ambiguousB.has(p.b.index)) continue;
    usedA.add(p.a.index);
    usedB.add(p.b.index);
    matched.push({ aIndex: p.a.index, bIndex: p.b.index, centroidDist: p.dist, vertexOverlap: p.overlap });
  }

  const removed = facesA.filter((f) => !usedA.has(f.index)).map((f) => f.index);
  const added = facesB.filter((f) => !usedB.has(f.index) && !ambiguousB.has(f.index)).map((f) => f.index);

  return { matched, removed, added, ambiguous };
}

// VERTEX_ANALYSIS.json stores b2Body as a numeric-keyed OBJECT (e.g. {"0":6}), an artifact of
// how vertex_analysis.js originally serialized it, while this script's freshly-parsed C12
// faces store it as a plain ARRAY (e.g. [6]). Comparing JSON.stringify of the two shapes would
// always report "changed" even when the values are identical -- normalize both to arrays
// before comparing, so this reflects a real value difference, not a representation artifact.
function normalizeB2Body(b2Body) {
  return Array.isArray(b2Body) ? b2Body : Object.values(b2Body);
}

function facesIdentical(faceA, faceB) {
  if (faceA.edgeCount !== faceB.edgeCount) return false;
  if (faceA.vertexCount !== faceB.vertexCount) return false;
  if (faceA.secCount !== faceB.secCount) return false;
  if (faceA.b1Len !== faceB.b1Len) return false;
  if (faceA.vertices.length !== faceB.vertices.length) return false;
  for (let i = 0; i < faceA.vertices.length; i++) {
    if (!vertClose(faceA.vertices[i], faceB.vertices[i], 1e-6)) return false;
  }
  return true;
}

// ============================================================
// Analysis per pair (C00 vs C03 recomputed here for a self-contained deliverable; C00 vs C12
// is the new comparison)
// ============================================================

function analyzePair(facesA, facesB, modelAName, modelBName) {
  const correspondence = matchFaces(facesA, facesB);

  const matchedDetails = correspondence.matched.map(({ aIndex, bIndex, centroidDist, vertexOverlap }) => {
    const fa = facesA.find((f) => f.index === aIndex);
    const fb = facesB.find((f) => f.index === bIndex);
    const identical = facesIdentical(fa, fb);
    const tokA = lookupTokens(modelAName, aIndex);
    const tokB = lookupTokens(modelBName, bIndex);
    const tokensChanged = tokA && tokB && tokA.tokens && tokB.tokens ? JSON.stringify(tokA.tokens) !== JSON.stringify(tokB.tokens) : null;
    return {
      aIndex,
      bIndex,
      centroidDist,
      vertexOverlap,
      identical,
      ecChanged: fa.edgeCount !== fb.edgeCount,
      vcChanged: fa.vertexCount !== fb.vertexCount,
      secCountChanged: fa.secCount !== fb.secCount,
      b1LenChanged: fa.b1Len !== fb.b1Len,
      b2BodyChanged: JSON.stringify(normalizeB2Body(fa.b2Body)) !== JSON.stringify(normalizeB2Body(fb.b2Body)),
      tokensA: tokA,
      tokensB: tokB,
      tokensChanged,
    };
  });

  const addedDetails = correspondence.added.map((bIndex) => {
    const fb = facesB.find((f) => f.index === bIndex);
    const adjacentToA = computeAdjacency(fb, facesA);
    const adjacentToB = computeAdjacency(fb, facesB);
    return {
      bIndex,
      edgeCount: fb.edgeCount,
      vertexCount: fb.vertexCount,
      secCount: fb.secCount,
      b1Len: fb.b1Len,
      tokens: lookupTokens(modelBName, bIndex),
      adjacentToOriginalFaces: adjacentToA,
      adjacentToModelFaces: adjacentToB,
    };
  });

  return {
    modelAName,
    modelBName,
    faceCountA: facesA.length,
    faceCountB: facesB.length,
    faceCountDiff: facesB.length - facesA.length,
    matched: matchedDetails,
    removed: correspondence.removed,
    added: addedDetails,
    ambiguous: correspondence.ambiguous,
  };
}

