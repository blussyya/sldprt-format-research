function summarizeModel(r, aName, bName) {
  const newFace = r.added[0];
  const bToA = new Map(r.matched.map((m) => [m.bIndex, m.aIndex]));
  const adjacentC00Indices = new Set(
    newFace.adjacentToModelFaces.map((a) => a.index).filter((bIdx) => bToA.has(bIdx)).map((bIdx) => bToA.get(bIdx))
  );
  const changedTokenFaces = r.matched.filter((m) => m.tokensChanged === true).map((m) => m.aIndex);
  const unchangedTokenFaces = r.matched.filter((m) => m.tokensChanged === false).map((m) => m.aIndex);
  const structurallyChangedFaces = r.matched.filter((m) => m.ecChanged || m.vcChanged || m.secCountChanged || m.b1LenChanged).map((m) => m.aIndex);

  console.log(`\n${bName}:`);
  console.log(`  New face: B${newFace.bIndex} (ec=${newFace.edgeCount}, vc=${newFace.vertexCount}, secCount=${newFace.secCount})`);
  console.log(`  New face real within-model adjacency (>=2 shared vertices): ${JSON.stringify(newFace.adjacentToModelFaces)}`);
  console.log(`  Translated to C00 indices: [${[...adjacentC00Indices].join(',')}]`);
  console.log(`  C00 faces with structural change (ec/vc/secCount/b1Len): [${structurallyChangedFaces.join(',')}]`);
  console.log(`  C00 faces with CHANGED tokens (matched, structurally identical): [${changedTokenFaces.filter((i) => !structurallyChangedFaces.includes(i)).join(',')}]`);
  console.log(`  C00 faces with UNCHANGED tokens: [${unchangedTokenFaces.join(',')}]`);

  const orientOf = (idx) => {
    const t = lookupTokens(aName, idx);
    return t ? t.orientation : '?';
  };
  const unrelatedChanged = changedTokenFaces.filter((i) => !structurallyChangedFaces.includes(i));
  console.log(`  Orientation of token-changed-but-structurally-unmodified faces: [${unrelatedChanged.map((i) => `${i}:${orientOf(i)}`).join(', ')}]`);

  return {
    newFaceIndex: newFace.bIndex,
    adjacentC00Indices: [...adjacentC00Indices],
    structurallyChangedFaces,
    tokenChangedUnmodifiedFaces: unrelatedChanged,
    tokenChangedUnmodifiedOrientations: unrelatedChanged.map((i) => orientOf(i)),
    unchangedTokenFaces,
  };
}

